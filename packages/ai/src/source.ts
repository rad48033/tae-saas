export interface TranscriptSegment {
  startSeconds: number;
  durationSeconds: number;
  text: string;
}

export interface Transcript {
  language: string;
  text: string;
  segments: TranscriptSegment[];
  isAutoGenerated?: boolean;
}

export interface VideoMeta {
  id: string;
  url: string;
  title: string;
  channelTitle: string;
  channelUrl?: string;
  description?: string;
  durationSeconds?: number;
  thumbnailUrl?: string;
  publishedAt?: string;
}

/** 모든 입력을 하나로 정규화한 문서. */
export interface SourceDocument {
  sourceType: SourceType;
  /** 원본 제목 (영상 제목 / 글 제목 / 카드뉴스 훅) */
  title: string;
  /** 채널명 · 블로그명 · 인스타 핸들 */
  author: string;
  url?: string;
  /** 원본 식별자 (영상 ID, URL 해시). 데모 결과의 slug/파일에 사용합니다. */
  id?: string;
  /** 자막 · 본문 · 캡션 등 근거 텍스트 */
  text: string;
  language: ContentLanguage | string;
  segments?: TranscriptSegment[];
  isAutoGenerated?: boolean;
  durationSeconds?: number;
  thumbnailUrl?: string;
  publishedAt?: string;
  description?: string;
}

export function sourceFromYoutube(video: VideoMeta, transcript: Transcript, language?: ContentLanguage): SourceDocument {
  return {
    sourceType: "youtube",
    title: video.title,
    author: video.channelTitle,
    url: video.url,
    id: video.id,
    text: transcript.text,
    language: language ?? transcript.language,
    segments: transcript.segments,
    ...(transcript.isAutoGenerated !== undefined ? { isAutoGenerated: transcript.isAutoGenerated } : {}),
    ...(video.durationSeconds !== undefined ? { durationSeconds: video.durationSeconds } : {}),
    ...(video.thumbnailUrl ? { thumbnailUrl: video.thumbnailUrl } : {}),
    ...(video.publishedAt ? { publishedAt: video.publishedAt } : {}),
    ...(video.description ? { description: video.description } : {}),
  };
}

/** 원본을 한 줄로 표현합니다. (UI 표시·프롬프트 메타데이터 공용) */
export function describeSource(source: SourceDocument): string {
  const label = SOURCE_LABELS[source.sourceType];
  const author = source.author.trim();
  return author ? `${label.ko} · ${author}` : label.ko;
}
