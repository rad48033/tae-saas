const FORMAT_SYSTEM: Record<ContentFormat, string[]> = {
  blog: BLOG_SYSTEM,
  instagram: INSTAGRAM_SYSTEM,
  facebook: FACEBOOK_SYSTEM,
};

const FORMAT_MAX_TOKENS: Record<ContentFormat, number> = {
  blog: 4096,
  instagram: 2600,
  facebook: 2200,
};

export function buildContentPrompt(input: ContentGenerationInput): ContentPrompt {
  const { video, transcript, target } = input;
  const { text: transcriptText, truncated } = truncateForPrompt(transcript.text, MAX_TRANSCRIPT_CHARS);

  const system = [
    ...FORMAT_SYSTEM[target.format],
    "",
    `언어: ${LANGUAGE_INSTRUCTIONS[target.language]}`,
  ].join("\n");

  const duration = video.durationSeconds
    ? `${Math.floor(video.durationSeconds / 60)}분 ${video.durationSeconds % 60}초`
    : "알 수 없음";

  const prompt = [
    "다음 유튜브 영상을 요청된 형식의 SNS 콘텐츠로 변환하세요.",
    "",
    "[영상 정보]",
    `- 제목: ${video.title}`,
    `- 채널: ${video.channelTitle}`,
    `- URL: ${video.url}`,
    `- 길이: ${duration}`,
    `- 자막 언어: ${transcript.language}${transcript.isAutoGenerated ? " (자동 생성 자막)" : ""}`,
    `- 발행 형식: ${target.format}`,
    `- 목표 언어: ${target.language}`,
    target.focusKeyword ? `- 1차 키워드(반드시 반영): ${target.focusKeyword}` : "- 1차 키워드: 자막에서 가장 검색될 만한 주제어를 직접 고르세요.",
    target.audience ? `- 대상 독자: ${target.audience}` : "",
    video.description ? `- 영상 설명(참고용): ${video.description.slice(0, 1200)}` : "",
    "",
    `[자막${truncated ? " (일부 생략됨)" : ""}]`,
    '"""',
    transcriptText,
    '"""',
    "",
    `위 자막만 근거로 ${target.format} 형식의 JSON을 작성하세요. 정보가 부족하면 없는 사실을 지어내지 말고 확인 가능한 범위에서 일반적인 배경 설명으로 보완하되 추측임을 드러내세요.`,
  ]
    .filter((line) => line !== "")
    .join("\n");

  return { system, prompt, maxTokens: FORMAT_MAX_TOKENS[target.format] };
}
