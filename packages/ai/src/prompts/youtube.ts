import type { ContentFormat, ContentLanguage } from "../schemas/content";
import { truncateForPrompt } from "../text";

export interface VideoMeta {
  id: string;
  url: string;
  title: string;
  channelTitle: string;
  channelUrl?: string;
  description?: string;
  durationSeconds?: number;
  thumbnailUrl?: string;
  publishedAt?: string;
}

export interface TranscriptSegment {
  startSeconds: number;
  durationSeconds: number;
  text: string;
}

export interface Transcript {
  language: string;
  text: string;
  segments: TranscriptSegment[];
  isAutoGenerated?: boolean;
}

export interface ContentGenerationInput {
  video: VideoMeta;
  transcript: Transcript;
  target: {
    language: ContentLanguage;
    format: ContentFormat;
    focusKeyword?: string;
    audience?: string;
  };
}

export interface ContentPrompt {
  system: string;
  prompt: string;
  maxTokens: number;
}

