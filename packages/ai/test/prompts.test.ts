import { describe, expect, it } from "vitest";

import { buildContentPrompt, MAX_TRANSCRIPT_CHARS, type ContentGenerationInput } from "../src/prompts/content";
import { buildPdfPrompt } from "../src/prompts/pdf";

const baseInput: ContentGenerationInput = {
  source: {
    sourceType: "youtube",
    id: "dQw4w9WgXcQ",
    url: "https://www.youtube.com/watch?v=dQw4w9WgXcQ",
    title: "스타트업 첫 100일 생존 전략",
    author: "창업 채널",
    durationSeconds: 754,
    language: "ko",
    text: "첫 100일은 제품보다 고객을 보는 시간입니다. 매주 5명의 고객과 이야기하세요.",
    segments: [{ startSeconds: 0, durationSeconds: 12, text: "첫 100일은 제품보다 고객을 보는 시간입니다." }],
    isAutoGenerated: true,
  },
  target: { language: "ko", format: "blog", focusKeyword: "스타트업 100일" },
};

describe("buildContentPrompt", () => {
  it("carries metadata and the blog JSON contract", () => {
    const prompt = buildContentPrompt(baseInput);
    expect(prompt.prompt).toContain("스타트업 첫 100일 생존 전략");
    expect(prompt.prompt).toContain("첫 100일은 제품보다 고객을 보는 시간입니다.");
    expect(prompt.prompt).toContain("스타트업 100일");
    expect(prompt.prompt).toContain("자동 생성");
    expect(prompt.prompt).toContain("발행 형식: blog");
    expect(prompt.system).toContain('"format": "blog"');
    expect(prompt.system).toContain("metaDescription");
    expect(prompt.system).toContain("JSON 객체 하나만");
  });

  it("asks for an influencer-grade long-form blog post", () => {
    const prompt = buildContentPrompt(baseInput);
    expect(prompt.system).toContain("2,000~3,500자");
    expect(prompt.system).toContain("executiveSummary");
    expect(prompt.system).toContain("H2 섹션은 4~5개");
    expect(prompt.system).toContain("faq는 3~5개");
    expect(prompt.system).toContain("태그는 검색어 중심 8~10개");
    expect(prompt.system).toContain("'장점과 한계'");
    expect(prompt.system).toContain("결론");
    // 3,500자 한국어 본문 + JSON 구조가 잘리지 않도록 여유 있는 상한
    expect(prompt.maxTokens).toBeGreaterThanOrEqual(7000);
  });

  it("uses the Instagram 10-slide carousel contract", () => {
    const prompt = buildContentPrompt({ ...baseInput, target: { ...baseInput.target, format: "instagram" } });
    expect(prompt.system).toContain("카드뉴스");
    expect(prompt.system).toContain("슬라이드는 정확히 10장");
    expect(prompt.system).toContain("1장 cover");
    expect(prompt.system).toContain("9장 caveat");
    expect(prompt.system).toContain("10장 summary");
    expect(prompt.system).toContain("15~20개");
    expect(prompt.system).toContain("slides");
    expect(prompt.system).toContain('"format": "instagram"');
    expect(prompt.maxTokens).toBeGreaterThanOrEqual(3500);
  });

  it("uses the Facebook ~20-line storytelling contract", () => {
    const prompt = buildContentPrompt({ ...baseInput, target: { ...baseInput.target, format: "facebook" } });
    expect(prompt.system).toContain("스토리텔링");
    expect(prompt.system).toContain("약 20줄");
    expect(prompt.system).toContain("closingQuestion");
    expect(prompt.system).toContain("bullets");
    expect(prompt.prompt).toContain("발행 형식: facebook");
    expect(prompt.maxTokens).toBeGreaterThanOrEqual(2500);
  });

  it("keeps every format grounded in the source text", () => {
    for (const format of ["blog", "instagram", "facebook"] as const) {
      const prompt = buildContentPrompt({ ...baseInput, target: { ...baseInput.target, format } });
      expect(prompt.system).toContain("원문에 없는 수치, 인용, 제품명, 인물은 만들지 않습니다");
      expect(prompt.prompt).toContain("위 원문만 근거로");
    }
  });

  it("labels a blog source as an article, not a transcript", () => {
    const prompt = buildContentPrompt({
      ...baseInput,
      source: {
        ...baseInput.source,
        sourceType: "blog",
        title: "첫 100일에 고객을 만나는 방법",
        author: "운영 노트",
        text: "첫 100일은 제품보다 고객을 보는 시간입니다.",
      },
    });
    expect(prompt.prompt).toContain("입력 유형: blog");
    expect(prompt.prompt).toContain("[본문]");
    expect(prompt.prompt).not.toContain("[자막]");
    expect(prompt.system).toContain("원문(본문)");
  });

  it("truncates long source text and marks the omission", () => {
    const long = "가".repeat(MAX_TRANSCRIPT_CHARS + 5_000);
    const prompt = buildContentPrompt({ ...baseInput, source: { ...baseInput.source, text: long } });
    expect(prompt.prompt).toContain("중략");
    expect(prompt.prompt.length).toBeLessThan(MAX_TRANSCRIPT_CHARS + 2_000);
  });

  it("writes English instructions for English targets", () => {
    const prompt = buildContentPrompt({ ...baseInput, target: { ...baseInput.target, language: "en" } });
    expect(prompt.system).toContain("Write in natural, idiomatic English");
  });
});

describe("buildPdfPrompt", () => {
  it("numbers pages and includes the schema guide", () => {
    const prompt = buildPdfPrompt({
      pages: [
        { page: 1, text: "INVOICE #2026-0042 Total 1,362.90" },
        { page: 2, text: "Terms: 30 days" },
      ],
      schema: "invoice",
    });
    expect(prompt.prompt).toContain("[1페이지]");
    expect(prompt.prompt).toContain("[2페이지]");
    expect(prompt.prompt).toContain("총 2페이지");
    expect(prompt.system).toContain("invoiceNumber");
  });
});
