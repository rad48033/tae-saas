import type { AspectPreset, Storyboard, SubtitleCue, SubtitleSet } from "./types";

/** 00:00:01,250 */
export function formatSrtTime(ms: number): string {
  const total = Math.max(0, Math.round(ms));
  const hours = Math.floor(total / 3_600_000);
  const minutes = Math.floor((total % 3_600_000) / 60_000);
  const seconds = Math.floor((total % 60_000) / 1000);
  const millis = total % 1000;
  return `${pad(hours, 2)}:${pad(minutes, 2)}:${pad(seconds, 2)},${pad(millis, 3)}`;
}

/** 0:00:01.25 (ASS는 1/100초) */
export function formatAssTime(ms: number): string {
  const total = Math.max(0, Math.round(ms / 10) * 10);
  const hours = Math.floor(total / 3_600_000);
  const minutes = Math.floor((total % 3_600_000) / 60_000);
  const seconds = Math.floor((total % 60_000) / 1000);
  const centis = Math.floor((total % 1000) / 10);
  return `${hours}:${pad(minutes, 2)}:${pad(seconds, 2)}.${pad(centis, 2)}`;
}

function pad(value: number, length: number): string {
  return String(value).padStart(length, "0");
}

/** .srt — UTF-8, CRLF는 쓰지 않습니다(플레이어 호환은 LF로 충분). */
export function buildSrt(cues: SubtitleCue[]): string {
  return (
    cues
      .map((cue, index) => {
        const text = cue.text.replace(/\r/g, "").trim();
        return `${index + 1}\n${formatSrtTime(cue.startMs)} --> ${formatSrtTime(cue.endMs)}\n${text}`;
      })
      .join("\n\n") + "\n"
  );
}

export interface AssOptions {
  preset: AspectPreset;
  fontName?: string;
  title?: string;
}

/**
 * .ass — ffmpeg `ass` 필터로 영상에 직접 태웁니다.
 * 폰트가 없으면 libass가 시스템 폰트로 대체합니다(fontsdir 환경변수 참고).
 */
export function buildAss(cues: SubtitleCue[], options: AssOptions): string {
  const { preset } = options;
  const fontName = options.fontName?.trim() || "Noto Sans CJK KR";
  const header = [
    "[Script Info]",
    "; Generated by @tae/video",
    options.title ? `Title: ${options.title.replace(/[\r\n]+/g, " ")}` : "Title: Storyboard",
    "ScriptType: v4.00+",
    `PlayResX: ${preset.width}`,
    `PlayResY: ${preset.height}`,
    "WrapStyle: 2",
    "ScaledBorderAndShadow: yes",
    "",
    "[V4+ Styles]",
    "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
    [
      "Style: Default",
      fontName,
      String(preset.subtitle.fontSize),
      // 본문: 흰색, 외곽선·그림자: 검정(박스 모드에서는 외곽선 색이 박스 채움색)
      "&H00FFFFFF",
      "&H000000FF",
      preset.subtitle.box ? "&H70000000" : "&H00000000",
      "&H80000000",
      "-1",
      "0",
      "0",
      "0",
      "100",
      "100",
      "0",
      "0",
      preset.subtitle.box ? "3" : "1",
      // 박스 모드에서 Outline 값은 글자와 박스 테두리 사이 여백입니다.
      String(preset.subtitle.box ? 16 : preset.subtitle.outline),
      String(preset.subtitle.box ? 0 : preset.subtitle.shadow),
      "2",
      "80",
      "80",
      String(preset.subtitle.marginV),
      "1",
    ].join(","),
    "",
    "[Events]",
    "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
  ];

  const events = cues.map((cue) => {
    const text = toAssText(cue.text, preset.subtitle.maxCharsPerLine, preset.subtitle.maxLines);
    return `Dialogue: 0,${formatAssTime(cue.startMs)},${formatAssTime(cue.endMs)},Default,,0,0,0,,${text}`;
  });

  return `${header.join("\n")}\n${events.join("\n")}\n`;
}

function toAssText(text: string, maxCharsPerLine: number, maxLines: number): string {
  return wrapText(text, maxCharsPerLine, maxLines)
    .map((line) => line.replace(/[{}]/g, "").replace(/\\/g, "／").trim())
    .filter(Boolean)
    .join("\\N");
}

/**
 * 자막 한 컷을 최대 줄 수·줄 길이에 맞춰 나눕니다.
 * 마지막 줄에 남는 단어는 길이를 넘겨도 모두 붙입니다(자막 누락 방지).
 */
export function wrapText(text: string, maxCharsPerLine: number, maxLines: number): string[] {
  const normalized = text.replace(/\s+/g, " ").trim();
  if (!normalized) return [];
  if (normalized.length <= maxCharsPerLine) return [normalized];

  const words = normalized.split(" ");

  // 두 줄일 때는 앞 줄을 꽉 채우고 마지막에 한두 단어만 남기는 대신,
  // 어절 경계에서 두 줄 길이가 가장 비슷한 지점을 고릅니다("…온 / 가족" 같은 어색한 끊김 방지).
  if (maxLines === 2 && words.length > 1) {
    let best: { first: string; second: string; score: number; fits: boolean } | null = null;
    for (let index = 1; index < words.length; index += 1) {
      const first = words.slice(0, index).join(" ");
      const second = words.slice(index).join(" ");
      const fits = first.length <= maxCharsPerLine && second.length <= maxCharsPerLine;
      // 두 줄 모두 한계 안에 들어오는 분할을 가장 우대합니다. 그런 분할이 없으면
      // 첫 줄만은 한계를 넘기지 않게 하고(읽는 순서가 먼저 깨지지 않도록), 남는 단어는 둘째 줄로 보냅니다.
      const firstOverflow = Math.max(0, first.length - maxCharsPerLine);
      const secondOverflow = Math.max(0, second.length - maxCharsPerLine);
      const score =
        (fits ? 0 : firstOverflow > 0 ? 2_000 + firstOverflow * 50 : 500 + secondOverflow * 5) +
        Math.abs(first.length - second.length);
      if (!best || score < best.score) best = { first, second, score, fits };
    }
    if (best) return [best.first, best.second];
  }

  const lines: string[] = [];
  let current = "";

  for (const word of words) {
    const candidate = current ? `${current} ${word}` : word;
    if (candidate.length <= maxCharsPerLine || current === "") {
      // 첫 단어가 한 줄보다 길면 그 단어만으로 줄을 채웁니다.
      current = current === "" && word.length > maxCharsPerLine ? word : candidate;
      continue;
    }

    if (lines.length >= maxLines - 1) {
      current = `${current} ${word}`;
      continue;
    }

    lines.push(current);
    current = word;
  }

  if (current) lines.push(current);
  return lines;
}

/**
 * 나레이션을 자막 컷으로 나눕니다.
 * 문장 부호 → 쉼표 → 글자 수 순서로 끊고, 재생 시간은 글자 수 비례로 배분합니다.
 */
export function splitNarrationIntoChunks(text: string, maxChars: number): string[] {
  const normalized = text.replace(/\s+/g, " ").trim();
  if (!normalized) return [];

  const sentences = normalized
    .split(/(?<=[.!?。？！]|다\.)\s+/)
    .map((sentence) => sentence.trim())
    .filter(Boolean);

  const chunks: string[] = [];
  let current = "";

  const flush = () => {
    if (current.trim()) chunks.push(current.trim());
    current = "";
  };

  for (const sentence of sentences.length > 0 ? sentences : [normalized]) {
    if (sentence.length <= maxChars) {
      if (`${current} ${sentence}`.trim().length > maxChars) flush();
      current = `${current} ${sentence}`.trim();
      continue;
    }

    // 긴 문장은 쉼표에서 한 번 끊어 봅니다.
    const parts = sentence
      .split(/,\s+|、\s*|，\s*/)
      .map((part) => part.trim())
      .filter(Boolean);

    for (const part of parts) {
      if (part.length <= maxChars) {
        if (`${current} ${part}`.trim().length > maxChars) flush();
        current = `${current} ${part}`.trim();
        continue;
      }

      const words = part.split(" ");
      for (const word of words) {
        if (`${current} ${word}`.trim().length > maxChars) flush();
        if (word.length > maxChars) {
          // 띄어쓰기 없는 긴 문자열(영어 URL 등)은 글자 수로 자릅니다.
          for (let start = 0; start < word.length; start += maxChars) {
            const slice = word.slice(start, start + maxChars);
            if (`${current} ${slice}`.trim().length > maxChars) flush();
            current = `${current} ${slice}`.trim();
          }
          continue;
        }
        current = `${current} ${word}`.trim();
      }
    }
  }

  flush();
  return chunks;
}

/**
 * 오디오 길이에 맞춰 컷별 시작/끝을 배분합니다.
 * 글자 수 비례 + 컷 사이 80ms 간격, 최소 700ms를 보장합니다.
 */
export function alignCueTimings(
  chunks: string[],
  startMs: number,
  durationMs: number,
  options: { gapMs?: number; minCueMs?: number } = {},
): SubtitleCue[] {
  if (chunks.length === 0) return [];
  const gapMs = options.gapMs ?? 80;
  const minCueMs = options.minCueMs ?? 700;

  const weights = chunks.map((chunk) => Math.max(1, chunk.replace(/\s+/g, "").length));
  const totalWeight = weights.reduce((sum, weight) => sum + weight, 0);
  const usable = Math.max(durationMs - gapMs * (chunks.length - 1), minCueMs * chunks.length);

  let cursor = startMs;
  return chunks.map((chunk, index) => {
    const weight = weights[index] ?? 1;
    const raw = (usable * weight) / totalWeight;
    const start = Math.round(cursor);
    const end = Math.round(start + Math.max(minCueMs, raw));
    cursor = end + gapMs;
    return { startMs: start, endMs: end, text: chunk };
  });
}

/** 스토리보드만으로 만드는 예비 자막 (오디오 실측 전). */
export function cuesFromStoryboard(storyboard: Storyboard, preset: AspectPreset): SubtitleCue[] {
  const cues: SubtitleCue[] = [];
  for (const scene of storyboard.scenes) {
    const chunks = splitNarrationIntoChunks(scene.narration, preset.subtitle.maxCharsPerCue);
    cues.push(...alignCueTimings(chunks, scene.startMs, scene.durationMs));
  }
  return cues;
}

export function subtitleSet(
  cues: SubtitleCue[],
  preset: AspectPreset,
  meta: { source: "stt" | "aligned"; provider: "openai" | "gemini" | "fallback"; title?: string; fontName?: string },
): SubtitleSet {
  return {
    cues,
    srt: buildSrt(cues),
    ass: buildAss(cues, { preset, ...(meta.title ? { title: meta.title } : {}), ...(meta.fontName ? { fontName: meta.fontName } : {}) }),
    source: meta.source,
    provider: meta.provider,
  };
}
