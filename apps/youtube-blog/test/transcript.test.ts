import { describe, expect, it } from "vitest";

import { normalizeTranscriptInput, transcriptFromText } from "../src/lib/transcript";

describe("manual transcript input", () => {
  it("removes timestamp-only lines and extra whitespace", () => {
    const input = "0:00\n첫 100일은 고객을 보는 시간입니다.\n\n0:12\n매주   5명의 고객과 이야기하세요.\n";
    const normalized = normalizeTranscriptInput(input);
    expect(normalized).toBe("첫 100일은 고객을 보는 시간입니다.\n\n매주 5명의 고객과 이야기하세요.");
  });

  it("keeps times that appear inside sentences", () => {
    expect(normalizeTranscriptInput("10:30에 시작합니다")).toBe("10:30에 시작합니다");
  });

  it("builds a Transcript object", () => {
    const transcript = transcriptFromText("가".repeat(300), "ko");
    expect(transcript.language).toBe("ko");
    expect(transcript.segments).toEqual([]);
    expect(transcript.isAutoGenerated).toBe(false);
    expect(transcript.text.length).toBe(300);
  });
});
