import type { Transcript } from "@tae/ai";

export const MAX_TRANSCRIPT_INPUT_CHARS = 200_000;
export const MIN_TRANSCRIPT_CHARS = 200;

/**
 * 유튜브 "스크립트 표시"에서 복사한 텍스트를 정리합니다.
 * - 타임스탬프만 있는 줄 제거
 * - 과도한 공백/빈 줄 정리
 */
export function normalizeTranscriptInput(input: string): string {
  return input
    .replace(/\r\n/g, "\n")
    .replace(/^\s*\d{1,2}:\d{2}(?::\d{2})?\s*$/gm, "")
    .replace(/[ \t]+/g, " ")
    .replace(/ ?\n ?/g, "\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

export function transcriptFromText(text: string, language: string): Transcript {
  return {
    language,
    text: normalizeTranscriptInput(text),
    segments: [],
    isAutoGenerated: false,
  };
}
