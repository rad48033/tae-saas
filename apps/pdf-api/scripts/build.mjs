import { build } from "esbuild";
import { cp, mkdir, rm, stat } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";

/**
 * Vercel 서버리스 함수용 번들.
 * pdf.js는 번들 밖에서 워커 모듈을 동적으로 불러오므로, 워커 파일을
 * 번들 옆(api/pdf.worker.mjs)에 복사해 함께 배포합니다.
 */
const appRoot = resolve(dirname(new URL(import.meta.url).pathname), "..");
const outfile = join(appRoot, "api/index.js");
const workerOut = join(appRoot, "api/pdf.worker.mjs");

await mkdir(join(appRoot, "api"), { recursive: true });
await rm(outfile, { force: true });
await rm(workerOut, { force: true });

await build({
  entryPoints: [join(appRoot, "src/vercel.ts")],
  outfile,
  bundle: true,
  platform: "node",
  target: "node20",
  format: "esm",
  sourcemap: false,
  minify: true,
  logLevel: "warning",
  // 렌더링용 네이티브 캔버스는 텍스트 추출에 필요 없음
  external: ["@napi-rs/canvas"],
  banner: {
    js: "// Generated by scripts/build.mjs — do not edit. Source: src/vercel.ts",
  },
});

const require = createRequire(import.meta.url);
const pdfjsRoot = dirname(require.resolve("pdfjs-dist/package.json"));
await cp(join(pdfjsRoot, "legacy/build/pdf.worker.mjs"), workerOut);

const bundleSize = (await stat(outfile)).size;
const workerSize = (await stat(workerOut)).size;
console.log(
  `[pdf-api] built api/index.js (${(bundleSize / 1024).toFixed(0)}KB) + pdf.worker.mjs (${(workerSize / 1024).toFixed(0)}KB)`,
);
